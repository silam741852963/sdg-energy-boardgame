class PixelFont:
    """Tiny dependency-free 5x5 glyph font, scaled with nearest-neighbor pixels."""

    glyph_width = 5
    glyph_height = 5

    def measure(self, text: str, scale: int) -> tuple[int, int]:
        if not text:
            return 0, self.glyph_height * scale
        return (len(text) * 6 - 1) * scale, self.glyph_height * scale

    def render(self, text: str, scale: int, color: tuple[int, int, int]) -> pygame.Surface:
        text = text.upper()
        width, height = self.measure(text, scale)
        surface = pygame.Surface((max(1, width), max(1, height)), pygame.SRCALPHA)
        for char_index, char in enumerate(text):
            glyph = _GLYPHS.get(char, _GLYPHS["?"])
            origin_x = char_index * 6 * scale
            for index, value in enumerate(glyph):
                if value == "1":
                    x = origin_x + (index % 5) * scale
                    y = (index // 5) * scale
                    surface.fill((*color, 255), (x, y, scale, scale))
        return surface
